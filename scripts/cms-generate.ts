const GENERATED_HEADER =
  'This file was generated by tanstack-keystone-starter cms:generate. Do not edit this file directly; edit cms.config.ts instead.'
const GENERATED_TS_HEADER = `// ${GENERATED_HEADER}\n`

type WriteResult = {
  filePath: string
  content: string
}

function stableJson(value: unknown): string {
  return `${JSON.stringify(sortJson(value), null, 2)}\n`
}

function sortJson(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortJson)
  if (!value || typeof value !== 'object') return value
  return Object.fromEntries(
    Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, child]) => [key, sortJson(child)]),
  )
}

function withGeneratedJsonHeader(value: unknown): string {
  return stableJson({ __generated: GENERATED_HEADER, ...asRecord(value) })
}

function asRecord(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {}
}

function publicConfigManifest(lists: ReturnType<typeof initialiseLists>) {
  return {
    artifactVersion: 2,
    generatedAt: null,
    generator: 'tanstack-keystone-starter cms:generate',
    source: {
      configPath: 'cms.config.ts',
      listKeys: lists.map((list) => list.key),
    },
    lists,
  }
}

function generatedTypes(lists: ReturnType<typeof initialiseLists>) {
  const listKeyUnion =
    lists.map((list) => JSON.stringify(list.key)).join(' | ') || 'never'
  const itemTypes = lists
    .map((list) => {
      const fields = list.fields
        .map((field) => {
          if (field.kind === 'relationship')
            return `  ${field.path}?: string${field.many ? '[]' : ''} | null`
          if (field.kind === 'checkbox' || field.kind === 'password')
            return `  ${field.path}?: boolean | null`
          if (field.kind === 'integer' || field.kind === 'float')
            return `  ${field.path}?: number | null`
          if (
            field.kind === 'json' ||
            field.kind === 'document' ||
            field.kind === 'image'
          )
            return `  ${field.path}?: unknown`
          if (field.kind === 'multiselect') return `  ${field.path}?: string[]`
          return `  ${field.path}?: string | null`
        })
        .join('\n')
      return `export type ${list.key}Item = {\n${fields}\n}`
    })
    .join('\n\n')
  return `${GENERATED_TS_HEADER}\nexport type CmsListKey = ${listKeyUnion}\n\n${itemTypes}\n`
}

function runtimeHelper() {
  return `${GENERATED_TS_HEADER}\nimport adminMeta from './admin-meta.json' assert { type: 'json' }\nimport manifest from './manifest.json' assert { type: 'json' }\n\nexport { adminMeta, manifest }\n`
}

type ResolvedCustomView = {
  sourcePath: string
  resolvedPath: string
  module: Record<string, unknown>
}

const customViewExportNames = new Set([
  'Field',
  'Cell',
  'CardValue',
  'controller',
  'allowedExportsOnCustomViews',
])

async function resolvePathFromConfig(root: string, sourcePath: string) {
  const configDirectory = root
  const candidates = [
    path.resolve(configDirectory, sourcePath),
    path.resolve(configDirectory, sourcePath, 'index'),
    ...['.ts', '.tsx', '.js', '.jsx'].map((extension) =>
      path.resolve(configDirectory, `${sourcePath}${extension}`),
    ),
    ...['.ts', '.tsx', '.js', '.jsx'].map((extension) =>
      path.resolve(configDirectory, sourcePath, `index${extension}`),
    ),
  ]
  for (const candidate of candidates) {
    try {
      await access(candidate)
      return candidate
    } catch {
      // Try the next Vite/TypeScript-compatible extension.
    }
  }
  const requireFromConfig = createRequire(
    pathToFileURL(path.join(root, 'cms.config.ts')),
  )
  try {
    return requireFromConfig.resolve(sourcePath)
  } catch {
    throw new Error(`module not found: ${sourcePath}`)
  }
}

async function resolveCustomViews(
  root: string,
  lists: ReturnType<typeof initialiseLists>,
) {
  const resolved = new Map<string, ResolvedCustomView>()
  for (const list of lists) {
    for (const field of list.fields) {
      const sourcePath = customViewPath(field)
      if (!sourcePath || resolved.has(sourcePath)) continue
      if (sourcePath.includes('\\')) {
        throw new Error(
          `Invalid custom view path for ${list.key}.${field.path}: ${JSON.stringify(sourcePath)} contains a backslash`,
        )
      }
      if (path.isAbsolute(sourcePath)) {
        throw new Error(
          `Invalid custom view path for ${list.key}.${field.path}: ${JSON.stringify(sourcePath)} must not be absolute`,
        )
      }
      let resolvedPath: string
      try {
        resolvedPath = await resolvePathFromConfig(root, sourcePath)
      } catch (error) {
        throw new Error(
          `Unable to resolve custom view for ${list.key}.${field.path} at ${JSON.stringify(sourcePath)}: ${error instanceof Error ? error.message : String(error)}`,
        )
      }
      let loaded: Record<string, unknown>
      try {
        loaded = (await import(pathToFileURL(resolvedPath).href)) as Record<
          string,
          unknown
        >
      } catch (error) {
        throw new Error(
          `Unable to load custom view for ${list.key}.${field.path} at ${JSON.stringify(sourcePath)}: ${error instanceof Error ? error.message : String(error)}`,
        )
      }
      const exports = Object.keys(loaded).filter((name) => name !== 'default')
      const invalidExport = exports.find(
        (name) => !customViewExportNames.has(name),
      )
      if (invalidExport) {
        throw new Error(
          `Invalid custom view export for ${list.key}.${field.path} at ${JSON.stringify(sourcePath)}: ${invalidExport}; supported exports are ${Array.from(customViewExportNames).join(', ')}`,
        )
      }
      const permittedExports = exports.filter((name) =>
        customViewExportNames.has(name),
      )
      if (permittedExports.length === 0) {
        throw new Error(
          `Custom view for ${list.key}.${field.path} at ${JSON.stringify(sourcePath)} must export at least one of Field, Cell, CardValue, or controller`,
        )
      }
      for (const exportName of ['Field', 'Cell', 'CardValue', 'controller']) {
        if (
          loaded[exportName] !== undefined &&
          typeof loaded[exportName] !== 'function'
        ) {
          throw new Error(
            `Invalid custom view export for ${list.key}.${field.path} at ${JSON.stringify(sourcePath)}: ${exportName} must be a function`,
          )
        }
      }
      resolved.set(sourcePath, { sourcePath, resolvedPath, module: loaded })
    }
  }
  return resolved
}

async function generatedViewModules(
  root: string,
  lists: ReturnType<typeof initialiseLists>,
) {
  const viewOrder = generateViewOrder(lists)
  const customViews = await resolveCustomViews(root, lists)
  const imports: string[] = []
  const modules: string[] = []
  const paths: string[] = []
  let importIndex = 0
  for (const view of viewOrder) {
    const custom = customViews.get(view)
    if (!custom) {
      modules.push('null')
      paths.push('null')
      continue
    }
    const localName = `customView${importIndex++}`
    imports.push(
      `import * as ${localName} from ${JSON.stringify(custom.resolvedPath)}`,
    )
    modules.push(localName)
    paths.push(JSON.stringify(custom.sourcePath))
  }
  return `${GENERATED_TS_HEADER}\n${imports.join('\n')}\n\nexport const VIEW_ORDER = ${JSON.stringify(viewOrder, null, 2)} as const\nexport const VIEW_MODULES = [${modules.join(', ')}] as const\nexport const VIEW_MODULE_PATHS = [${paths.join(', ')}] as const\n`
}

async function buildArtifacts(
  root: string,
  cmsDir: string,
): Promise<WriteResult[]> {
  const lists = initialiseLists(cmsConfig)
  const schemaGraphql = `# ${GENERATED_HEADER}\n\n${printSchema(getCmsGraphQLSchema())}\n`
  const schemaPrisma = printCmsPrismaSchema(lists, cmsConfig.db)
  const viewOrder = generateViewOrder(lists)
  const viewModules = await generatedViewModules(root, lists)

  const artifacts: WriteResult[] = [
    {
      filePath: path.join(cmsDir, 'manifest.json'),
      content: withGeneratedJsonHeader(publicConfigManifest(lists)),
    },
    {
      filePath: path.join(cmsDir, 'admin-meta.json'),
      content: withGeneratedJsonHeader(getAdminMeta()),
    },
    { filePath: path.join(cmsDir, 'schema.graphql'), content: schemaGraphql },
    {
      filePath: path.join(cmsDir, 'view-order.json'),
      content: withGeneratedJsonHeader({ viewOrder: generateViewOrder(lists) }),
    },
    {
      filePath: path.join(cmsDir, 'view-order.ts'),
      content: `${GENERATED_TS_HEADER}\nexport const VIEW_ORDER = ${JSON.stringify(viewOrder, null, 2)} as const\n`,
    },
    { filePath: path.join(cmsDir, 'view-modules.ts'), content: viewModules },
    { filePath: path.join(cmsDir, 'types.ts'), content: generatedTypes(lists) },
    { filePath: path.join(cmsDir, 'runtime.ts'), content: runtimeHelper() },
    { filePath: path.join(cmsDir, 'schema.prisma'), content: schemaPrisma },
    {
      filePath: path.join(root, 'prisma/schema.prisma'),
      content: schemaPrisma,
    },
  ]

  const artifactHashes = Object.fromEntries(
    artifacts.map((artifact) => [
      path.relative(root, artifact.filePath),
      createHash('sha256').update(artifact.content).digest('hex'),
    ]),
  )
  artifacts.push({
    filePath: path.join(cmsDir, 'artifact-hash.json'),
    content: withGeneratedJsonHeader({
      artifactVersion: 1,
      artifacts: artifactHashes,
    }),
  })

  return artifacts
}

async function fileMatches(filePath: string, content: string) {
  try {
    return (await readFile(filePath, 'utf8')) === content
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false
    throw error
  }
}

async function main() {
  const command = process.argv.includes('--check') ? 'check' : 'generate'
  const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
  const cmsDir = path.join(root, '.cms')
  const artifacts = await buildArtifacts(root, cmsDir)

  if (command === 'check') {
    const drifted = []
    for (const artifact of artifacts) {
      if (!(await fileMatches(artifact.filePath, artifact.content)))
        drifted.push(path.relative(root, artifact.filePath))
    }
    if (drifted.length) {
      throw new Error(
        `CMS generated artifacts are out of date. Run npm run cms:generate. Drifted files: ${drifted.join(', ')}`,
      )
    }
    console.log('CMS generated artifacts are up to date.')
    return
  }

  for (const artifact of artifacts) {
    await mkdir(path.dirname(artifact.filePath), { recursive: true })
    await writeFile(artifact.filePath, artifact.content)
  }
  console.log(`Generated ${artifacts.length} CMS artifacts.`)
}

await main()
