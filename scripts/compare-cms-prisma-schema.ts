import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

function normalizeSchema(schema: string) {
  return schema
    .split('\n')
    .filter(
      (line) =>
        !line.startsWith('// This file was generated') &&
        !line.startsWith('// Do not edit this file'),
    )
    .map((line) => line.trim())
    .filter(Boolean)
    .join('\n')
}

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const current = await readFile(path.join(root, 'prisma/schema.prisma'), 'utf8')
const generated = await readFile(path.join(root, '.cms/schema.prisma'), 'utf8')

if (normalizeSchema(current) !== normalizeSchema(generated)) {
  throw new Error(
    'Generated .cms/schema.prisma differs from prisma/schema.prisma. Run npm run cms:generate and promote .cms/schema.prisma to prisma/schema.prisma, then run npm run db:generate/db:push as needed.',
  )
}

console.log(
  'Generated .cms/schema.prisma matches prisma/schema.prisma after whitespace/header normalization.',
)
