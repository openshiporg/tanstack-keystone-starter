import type { CmsDbConfig } from './config'
import type { CmsField, CmsList } from './types'

const GENERATED_PRISMA_HEADER = `// This file was generated by tanstack-keystone-starter cms:generate.\n// Do not edit this file directly; edit cms.config.ts instead.`

export function resolveCmsPrismaDatasourceUrl(
  configuredUrl: string | undefined,
  environment: NodeJS.ProcessEnv = process.env,
) {
  const envMatch = configuredUrl?.match(/^env\((["'])([^"']+)\1\)$/)
  if (envMatch) {
    const value = environment[envMatch[2]]
    if (value) return value
    throw new Error(`${envMatch[2]} is required by cmsConfig.db.url`)
  }
  if (configuredUrl) return configuredUrl
  if (environment.DATABASE_URL) return environment.DATABASE_URL
  throw new Error('DATABASE_URL is required by the Prisma CMS datasource')
}

function parseRelationRef(ref: string) {
  const [listKey, fieldPath] = ref.split('.')
  if (!listKey) throw new Error(`Invalid relationship ref ${ref}`)
  return { listKey, fieldPath }
}

function resolvedRelationshipMetadata(list: CmsList, field: CmsField) {
  return list.resolvedDbFields?.[field.path]?.relationship
}

function isRequired(field: CmsField) {
  return (
    field.graphql?.isNonNull?.create === true ||
    field.isNonNull?.[0] === true ||
    field.validation?.isRequired === true
  )
}

function isPrismaNullable(field: CmsField) {
  if (field.kind === 'id') return false
  if (field.db?.isNullable === true) return true
  if (field.db?.isNullable === false) return false
  if (
    field.graphql?.isNonNull?.create === true ||
    field.isNonNull?.[0] === true
  )
    return false
  if (
    field.kind === 'text' ||
    field.kind === 'checkbox' ||
    field.kind === 'document' ||
    field.kind === 'structure' ||
    field.kind === 'multiselect'
  )
    return false
  return !isRequired(field)
}

function idPrismaType(field: CmsField) {
  return field.fieldMeta?.idFieldKind === 'autoincrement' ? 'Int' : 'String'
}

function prismaEnumTypeName(list: CmsList, field: CmsField) {
  return `${list.key}${field.path.charAt(0).toUpperCase()}${field.path.slice(1)}Type`
}

function scalarPrismaType(
  field: CmsField,
  list: CmsList,
  provider: CmsDbConfig['provider'],
) {
  if (field.kind === 'id') return idPrismaType(field)
  if (field.kind === 'select' && field.fieldMeta?.type === 'integer')
    return 'Int'
  if (field.kind === 'select' && field.fieldMeta?.type === 'enum')
    return provider === 'sqlite' ? 'String' : prismaEnumTypeName(list, field)
  if (field.kind === 'text' || field.kind === 'select') return 'String'
  if (field.kind === 'decimal') return 'Decimal'
  if (field.kind === 'bigInt') return 'BigInt'
  if (field.kind === 'timestamp') return 'DateTime'
  if (field.kind === 'calendarDay')
    return provider === 'sqlite' ? 'String' : 'DateTime'
  if (field.kind === 'password') return 'String'
  if (field.kind === 'checkbox') return 'Boolean'
  if (field.kind === 'integer') return 'Int'
  if (field.kind === 'float') return 'Float'
  if (
    field.kind === 'json' ||
    field.kind === 'document' ||
    field.kind === 'multiselect'
  )
    return 'Json'
  if (field.kind === 'structure')
    return provider === 'sqlite' ? 'String' : 'Json'
  if (field.kind === 'file') return 'Json'
  if (field.kind === 'image') return 'Json'
  return null
}

function idDefaultAttribute(field: CmsField) {
  const idFieldKind = field.fieldMeta?.idFieldKind
  if (idFieldKind === 'uuid') return '@default(uuid())'
  if (idFieldKind === 'autoincrement') return '@default(autoincrement())'
  return '@default(cuid())'
}

function defaultAttribute(field: CmsField, provider: CmsDbConfig['provider']) {
  if (field.kind === 'id') return idDefaultAttribute(field)
  if (field.db?.prismaDefault) return `@default(${field.db.prismaDefault})`
  if (field.db?.isNullable === true && field.defaultValue === '')
    return undefined
  if (field.kind === 'password' && field.defaultValue === undefined)
    return undefined
  if (field.defaultValue === undefined) return undefined
  if (field.kind === 'password')
    return `@default(${JSON.stringify(String(field.defaultValue))})`
  if (
    field.kind === 'timestamp' &&
    field.defaultValue &&
    typeof field.defaultValue === 'object' &&
    !Array.isArray(field.defaultValue) &&
    (field.defaultValue as { kind?: unknown }).kind === 'now'
  )
    return '@default(now())'
  if (field.kind === 'checkbox')
    return `@default(${Boolean(field.defaultValue)})`
  if (field.kind === 'integer' || field.kind === 'float')
    return `@default(${String(field.defaultValue)})`
  if (field.kind === 'select' && field.fieldMeta?.type === 'integer') {
    return `@default(${String(field.defaultValue)})`
  }
  if (field.kind === 'select' && field.fieldMeta?.type === 'enum')
    return provider === 'sqlite'
      ? `@default(${JSON.stringify(String(field.defaultValue))})`
      : `@default(${String(field.defaultValue)})`
  if (
    field.kind === 'text' ||
    field.kind === 'select' ||
    field.kind === 'calendarDay'
  ) {
    return `@default(${JSON.stringify(String(field.defaultValue))})`
  }
  if (field.kind === 'decimal' || field.kind === 'bigInt') {
    return `@default(${JSON.stringify(String(field.defaultValue))})`
  }
  if (field.kind === 'multiselect')
    return `@default(${JSON.stringify(JSON.stringify(field.defaultValue ?? []))})`
  if (
    field.kind === 'document' ||
    field.kind === 'structure' ||
    field.kind === 'json'
  )
    return `@default(${JSON.stringify(JSON.stringify(field.defaultValue))})`
  return undefined
}

function shouldOwnRelationField(list: CmsList, field: CmsField) {
  const relationship = resolvedRelationshipMetadata(list, field)
  if (!relationship) return !field.many
  if (relationship.ownership === 'shared') return false
  return relationship.ownership === 'own'
}

function relationAttribute(
  field: CmsField,
  relationship?: ReturnType<typeof resolvedRelationshipMetadata>,
  foreignKey?: string,
) {
  const relationName =
    relationship?.joinTableName ??
    relationship?.relationArgs?.relationName ??
    relationship?.relationName ??
    field.db?.relationName
  const args: string[] = []
  if (relationName) args.push(JSON.stringify(relationName))
  if (foreignKey) {
    const referencesFieldPath =
      relationship?.relationArgs?.referencesFieldPath ??
      relationship?.referencesFieldPath ??
      'id'
    const onDelete =
      relationship?.relationArgs?.onDelete ?? relationship?.onDelete
    const onUpdate =
      relationship?.relationArgs?.onUpdate ?? relationship?.onUpdate
    args.push(`fields: [${foreignKey}]`, `references: [${referencesFieldPath}]`)
    if (onDelete && onDelete !== 'SetNull') args.push(`onDelete: ${onDelete}`)
    if (onUpdate && onUpdate !== 'Cascade') args.push(`onUpdate: ${onUpdate}`)
  }
  return args.length ? ` @relation(${args.join(', ')})` : ''
}

function renderScalarField(
  list: CmsList,
  field: CmsField,
  provider: CmsDbConfig['provider'],
) {
  const type = scalarPrismaType(field, list, provider)
  if (!type) return []

  if (
    (field.kind === 'image' || field.kind === 'file') &&
    field.db?.extendPrismaSchema
  ) {
    return field.db
      .extendPrismaSchema(field.path)
      .split('\n')
      .map((line) => line.trim())
      .filter(Boolean)
  }

  const attributes = []
  if (field.kind === 'id') attributes.push('@id')
  const defaultValue = defaultAttribute(field, provider)
  if (defaultValue) attributes.push(defaultValue)
  if (field.db?.isUnique) attributes.push('@unique')
  if (field.db?.updatedAt) attributes.push('@updatedAt')
  if (field.db?.map) attributes.push(`@map(${JSON.stringify(field.db.map)})`)
  if (
    field.kind === 'calendarDay' &&
    (provider === 'postgresql' || provider === 'mysql')
  )
    attributes.push('@db.Date')
  if (
    field.kind === 'decimal' &&
    (provider === 'postgresql' || provider === 'mysql')
  ) {
    const precision = Number(field.fieldMeta?.precision ?? 65)
    const scale = Number(field.fieldMeta?.scale ?? 30)
    attributes.push(`@db.Decimal(${precision}, ${scale})`)
  }

  const optional = isPrismaNullable(field) ? '?' : ''
  return [
    `${field.path} ${type}${optional}${attributes.length ? ` ${attributes.join(' ')}` : ''}`,
  ]
}

function renderRelationshipField(
  list: CmsList,
  field: CmsField,
  _listsByKey: Map<string, CmsList>,
) {
  const relationship = resolvedRelationshipMetadata(list, field)
  const relatedRef = field.ref ? parseRelationRef(field.ref) : null
  const relatedListKey = relationship?.refListKey ?? relatedRef?.listKey
  if (!relatedListKey) return []
  const type = field.many ? `${relatedListKey}[]` : `${relatedListKey}?`
  const ownsRelation = shouldOwnRelationField(list, field)

  if (!ownsRelation)
    return [`${field.path} ${type}${relationAttribute(field, relationship)}`]

  const foreignKey = relationship?.foreignKeyFieldName ?? `${field.path}Id`
  const foreignKeyType = relationship?.foreignKeyScalarType ?? 'String'
  const foreignKeyMap = relationship?.foreignKeyMap
  const foreignKeyAttributes = [
    relationship?.relationKind === 'one' ? '@unique' : undefined,
    foreignKeyMap ? `@map(${JSON.stringify(foreignKeyMap)})` : undefined,
  ].filter(Boolean)
  const foreignKeyColumn = `${foreignKey} ${foreignKeyType}?${foreignKeyAttributes.length ? ` ${foreignKeyAttributes.join(' ')}` : ''}`
  return [
    foreignKeyColumn,
    `${field.path} ${type}${relationAttribute(field, relationship, foreignKey)}`,
  ]
}

function renderModel(
  list: CmsList,
  listsByKey: Map<string, CmsList>,
  provider: CmsDbConfig['provider'],
) {
  const lines = [`model ${list.key} {`]
  for (const field of list.fields) {
    const fieldLines =
      field.kind === 'relationship'
        ? renderRelationshipField(list, field, listsByKey)
        : renderScalarField(list, field, provider)
    for (const line of fieldLines) lines.push(`  ${line}`)
  }
  for (const sourceList of listsByKey.values()) {
    for (const sourceField of sourceList.fields) {
      if (sourceField.kind !== 'relationship') continue
      const relationship = resolvedRelationshipMetadata(sourceList, sourceField)
      if (relationship?.refListKey !== list.key || relationship.oppositeExists)
        continue
      const hiddenField = `from_${sourceList.key}_${sourceField.path}`
      lines.push(
        `  ${hiddenField} ${sourceList.key}[]${relationAttribute(sourceField, relationship)}`,
      )
    }
  }
  for (const line of list.db?.extraPrismaFields ?? []) lines.push(`  ${line}`)
  for (const field of list.fields) {
    if (
      field.kind !== 'relationship' &&
      field.db?.isIndexed === true &&
      field.db?.isUnique !== true
    )
      lines.push(`  @@index([${field.path}])`)
    if (field.kind !== 'relationship') continue
    const relationship = resolvedRelationshipMetadata(list, field)
    if (
      relationship?.ownership === 'own' &&
      relationship.foreignKeyFieldName &&
      relationship.relationKind !== 'one'
    )
      lines.push(`  @@index([${relationship.foreignKeyFieldName}])`)
  }
  if (list.prisma?.mapping)
    lines.push(`  @@map(${JSON.stringify(list.prisma.mapping)})`)
  lines.push('}')
  return lines.join('\n')
}

function renderPrismaEnums(
  lists: CmsList[],
  provider: CmsDbConfig['provider'],
) {
  if (provider === 'sqlite') return ''
  return lists
    .flatMap((list) =>
      list.fields.flatMap((field) => {
        if (field.kind !== 'select' || field.fieldMeta?.type !== 'enum')
          return []
        const values = (field.options ?? []).map((option) =>
          String(option.value),
        )
        return [
          `enum ${prismaEnumTypeName(list, field)} {\n${values.map((value) => `  ${value}`).join('\n')}\n}`,
        ]
      }),
    )
    .join('\n\n')
}

export function printCmsPrismaSchema(
  lists: CmsList[],
  dbConfig: CmsDbConfig = {},
) {
  const listsByKey = new Map(lists.map((list) => [list.key, list]))
  const provider = dbConfig.provider ?? 'postgresql'
  const enums = renderPrismaEnums(lists, provider)
  return `${GENERATED_PRISMA_HEADER}\n\ngenerator client {\n  provider = "prisma-client"\n  output   = "../src/generated/prisma"\n}\n\ndatasource db {\n  provider = "${provider}"\n}\n\n${lists.map((list) => renderModel(list, listsByKey, provider)).join('\n\n')}${enums ? `\n\n${enums}` : ''}\n`
}
